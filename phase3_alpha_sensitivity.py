# ── helper: sweep alpha on precomputed anomaly + rule scores ──────────────────
def sweep_alpha(anomaly_scores, rule_scores, y_true, threshold=0.45,
                alphas=None):
    if alphas is None:
        alphas = np.round(np.arange(0.0, 1.05, 0.05), 2)
    from sklearn.metrics import f1_score, confusion_matrix
    rows = []
    for a in alphas:
        ts    = a * rule_scores + (1 - a) * anomaly_scores
        y_pred = (ts >= threshold).astype(int)
        f1    = f1_score(y_true, y_pred, zero_division=0)
        cm    = confusion_matrix(y_true, y_pred, labels=[0,1])
        tn,fp,fn,tp = cm.ravel()
        fpr   = fp/(fp+tn) if (fp+tn)>0 else 0
        rows.append({'alpha': a, 'f1': round(f1,4), 'fpr': round(fpr,4)})
    return pd.DataFrame(rows)


